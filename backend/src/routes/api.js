import { Router } from 'express';
import * as c from '../controllers/api.js';
export const router = Router();
const wrap = handler => (req, res, next) => Promise.resolve(handler(req, res)).catch(next);
router.get('/the-loai', wrap(c.listGenres));
router.post('/the-loai', wrap(c.createGenre));
router.put('/the-loai/:id', wrap(c.updateGenre));
router.delete('/the-loai/:id', wrap(c.deleteGenre));
router.get('/phim/stats', wrap(c.movieStats));
router.get('/phim', wrap(c.listMovies));
router.get('/phim/:id', wrap(c.getMovie));
router.post('/phim', wrap(c.createMovie));
router.put('/phim/:id', wrap(c.updateMovie));
router.delete('/phim/:id', wrap(c.deleteMovie));
router.post('/phim/:id/danh-gia', wrap(c.reviewMovie));
